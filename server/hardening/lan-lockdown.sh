#!/usr/bin/env bash
# Makes remote-access services reachable only from this Mac and from Tailscale.
#
# Blocks incoming SSH (22), Screen Sharing (5900), the MAGI server (8080) and mosh
# (UDP 60000-61000) on every physical interface (Ethernet, Wi-Fi, Thunderbolt), using
# macOS' built-in pf firewall. Tailscale traffic arrives on a utun interface and is not
# affected; neither is localhost. Re-applied at every boot by a LaunchDaemon.
#
#   sudo ./server/hardening/lan-lockdown.sh install                  # firewall rules
#   sudo ./server/hardening/lan-lockdown.sh install --ssh-keys-only  # + disable SSH passwords
#   sudo ./server/hardening/lan-lockdown.sh status
#   sudo ./server/hardening/lan-lockdown.sh uninstall
set -euo pipefail

ANCHOR="com.apple/250.magi-lan-lockdown"     # evaluated by the stock /etc/pf.conf ("anchor com.apple/*")
RULES="/etc/pf.anchors/magi-lan-lockdown"
LOADER="/usr/local/libexec/magi-lan-lockdown-load"
LABEL="com.local.magi.lan-lockdown"
PLIST="/Library/LaunchDaemons/$LABEL.plist"
SSHD_DROPIN="/etc/ssh/sshd_config.d/000-magi-keys-only.conf"   # 000- so it wins over 100-macos.conf
TCP_PORTS="${MAGI_LOCKDOWN_TCP_PORTS:-22 5900 8080}"
UDP_PORTS="${MAGI_LOCKDOWN_UDP_PORTS:-60000:61000}"

[[ $EUID -eq 0 ]] || { echo "Run with sudo." >&2; exit 1; }
ACTION="${1:-status}"; shift || true
KEYS_ONLY=0
for arg in "$@"; do [[ $arg == --ssh-keys-only ]] && KEYS_ONLY=1; done

write_loader() {
  mkdir -p "$(dirname "$LOADER")"
  cat > "$LOADER" <<EOF
#!/bin/bash
# Generated by magi/server/hardening/lan-lockdown.sh — rebuilds and loads the pf anchor.
IFACES=\$(/usr/sbin/networksetup -listallhardwareports | /usr/bin/awk '/^Device: /{printf "%s ", \$2}')
{
  echo "# Generated \$(date) — physical interfaces: \$IFACES"
  # Track the Mac's own outgoing UDP so replies (DNS, QUIC, …) that land on a port in the
  # mosh range below are matched by state and not dropped. New inbound UDP is still blocked.
  echo "pass out proto udp from any to any keep state"
  echo "block drop in quick on { \$IFACES} proto tcp from any to any port { $TCP_PORTS }"
  echo "block drop in quick on { \$IFACES} proto udp from any to any port $UDP_PORTS"
} > "$RULES"
# At boot, give com.apple.pfctl time to load /etc/pf.conf first (that would reset anchors).
[[ "\${1:-}" == "--boot" ]] && sleep 15
/sbin/pfctl -s info 2>/dev/null | /usr/bin/grep -q "Status: Enabled" || /sbin/pfctl -E >/dev/null 2>&1
/sbin/pfctl -a "$ANCHOR" -f "$RULES"
EOF
  chmod 755 "$LOADER"
}

write_plist() {
  cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key><string>$LABEL</string>
    <key>ProgramArguments</key><array><string>$LOADER</string><string>--boot</string></array>
    <key>RunAtLoad</key><true/>
</dict>
</plist>
EOF
  chmod 644 "$PLIST"
}

case "$ACTION" in
  install)
    write_loader
    write_plist
    "$LOADER"
    launchctl bootout system "$PLIST" 2>/dev/null || true
    launchctl bootstrap system "$PLIST"
    if [[ $KEYS_ONLY == 1 ]]; then
      USER_HOME=$(dscl . -read "/Users/${SUDO_USER:-$USER}" NFSHomeDirectory | awk '{print $2}')
      if ! grep -q -E '^(ssh-|ecdsa-|sk-)' "$USER_HOME/.ssh/authorized_keys" 2>/dev/null; then
        echo "Refusing --ssh-keys-only: no keys in $USER_HOME/.ssh/authorized_keys (you'd be locked out)." >&2
        exit 1
      fi
      printf 'PasswordAuthentication no\nKbdInteractiveAuthentication no\n' > "$SSHD_DROPIN"
      /usr/sbin/sshd -t || { rm -f "$SSHD_DROPIN"; echo "sshd config test failed — reverted." >&2; exit 1; }
      echo "SSH: passwords disabled, keys only (applies to new connections)."
    fi
    echo "Installed. Rules:"; pfctl -a "$ANCHOR" -sr 2>/dev/null
    ;;
  status)
    pfctl -s info 2>/dev/null | head -1
    echo "Anchor $ANCHOR:"; pfctl -a "$ANCHOR" -sr 2>/dev/null || echo "  (empty)"
    launchctl print "system/$LABEL" >/dev/null 2>&1 && echo "Boot job: loaded" || echo "Boot job: not loaded"
    [[ -f $SSHD_DROPIN ]] && echo "SSH: keys only" || echo "SSH: passwords allowed (macOS default)"
    ;;
  uninstall)
    launchctl bootout system "$PLIST" 2>/dev/null || true
    pfctl -a "$ANCHOR" -F all 2>/dev/null || true
    rm -f "$PLIST" "$LOADER" "$RULES" "$SSHD_DROPIN"
    echo "Removed rules, boot job and the SSH keys-only setting. pf itself stays enabled with no MAGI rules;"
    echo "if iCloud Private Relay still reports \"incompatible\", run: sudo pfctl -d"
    ;;
  *) echo "Usage: sudo $0 install [--ssh-keys-only] | status | uninstall" >&2; exit 1 ;;
esac
